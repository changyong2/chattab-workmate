assert.throws(()=>X.decode(X.encode(p)+'!'));
assert(!X.complete({...answers,workSatisfaction:6}));
assert(!X.complete({...answers,lifeRules:[0]}));
assert(!X.complete({...answers,workPriorities:[0,1,2,3]}));
assert(!X.complete({...answers,workPriorities:[0,8]}));
